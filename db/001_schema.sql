-- Buoc Chan Viet: logical data model in section 3.1.5 (25 relations).
-- Run against an empty PostgreSQL database with: psql -X -v ON_ERROR_STOP=1 -d bcv -f db/001_schema.sql
BEGIN;

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    avatar TEXT,
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_preference (
    user_preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(user_id),
    activity_level VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE place_type (
    place_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE user_preference_place_type (
    user_preference_id BIGINT NOT NULL REFERENCES user_preference(user_preference_id),
    place_type_id BIGINT NOT NULL REFERENCES place_type(place_type_id),
    PRIMARY KEY (user_preference_id, place_type_id)
);

CREATE TABLE step_data (
    step_data_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    source_data_id VARCHAR(255) NOT NULL,
    step_count INTEGER NOT NULL CHECK (step_count >= 0),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, source_data_id),
    CHECK (end_time >= start_time)
);

CREATE TABLE region (
    region_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE place (
    place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id BIGINT NOT NULL REFERENCES region(region_id),
    place_type_id BIGINT NOT NULL REFERENCES place_type(place_type_id),
    name VARCHAR(200) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    introduction TEXT,
    highlights TEXT,
    rating NUMERIC(3,2) CHECK (rating BETWEEN 0 AND 5),
    rating_count INTEGER NOT NULL DEFAULT 0 CHECK (rating_count >= 0),
    status VARCHAR(20) NOT NULL
);

CREATE TABLE virtual_location (
    virtual_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(user_id),
    region_id BIGINT NOT NULL REFERENCES region(region_id),
    nearest_place_id BIGINT REFERENCES place(place_id),
    latitude NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE place_image (
    place_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES place(place_id),
    image_key TEXT NOT NULL
);

CREATE TABLE journey (
    journey_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    start_place_id BIGINT REFERENCES place(place_id),
    start_latitude NUMERIC(9,6) NOT NULL CHECK (start_latitude BETWEEN -90 AND 90),
    start_longitude NUMERIC(9,6) NOT NULL CHECK (start_longitude BETWEEN -180 AND 180),
    destination_place_id BIGINT NOT NULL REFERENCES place(place_id),
    distance NUMERIC(10,2) NOT NULL CHECK (distance >= 0),
    required_steps INTEGER NOT NULL CHECK (required_steps > 0),
    recorded_steps INTEGER NOT NULL DEFAULT 0 CHECK (recorded_steps >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);
CREATE UNIQUE INDEX journey_one_active_per_user ON journey (user_id) WHERE status = 'IN_PROGRESS';

CREATE TABLE user_discovered_place (
    user_discovered_place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    place_id BIGINT NOT NULL REFERENCES place(place_id),
    discovered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, place_id)
);

CREATE TABLE card (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL UNIQUE REFERENCES place(place_id),
    name VARCHAR(150) NOT NULL,
    image_key TEXT,
    description TEXT,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE collection (
    collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE collection_card (
    collection_card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES collection(collection_id),
    card_id BIGINT NOT NULL REFERENCES card(card_id),
    UNIQUE (collection_id, card_id)
);

CREATE TABLE user_card (
    user_card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    card_id BIGINT NOT NULL REFERENCES card(card_id),
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, card_id)
);

CREATE TABLE item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    item_type VARCHAR(30) NOT NULL,
    description TEXT,
    effect_value NUMERIC(10,2),
    effective_range INTEGER CHECK (effective_range >= 0),
    usage_limit INTEGER CHECK (usage_limit >= 0),
    status VARCHAR(20) NOT NULL
);

CREATE TABLE user_item (
    user_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    item_id BIGINT NOT NULL REFERENCES item(item_id),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, item_id)
);

CREATE TABLE quest (
    quest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward_item_id BIGINT REFERENCES item(item_id),
    name VARCHAR(200) NOT NULL,
    quest_type VARCHAR(20) NOT NULL,
    condition_type VARCHAR(50) NOT NULL,
    target_value INTEGER NOT NULL CHECK (target_value > 0),
    cycle_type VARCHAR(20) NOT NULL,
    reward_quantity INTEGER CHECK (reward_quantity > 0),
    status VARCHAR(20) NOT NULL,
    CHECK ((reward_item_id IS NULL) = (reward_quantity IS NULL))
);

CREATE TABLE quest_progress (
    quest_progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    quest_id BIGINT NOT NULL REFERENCES quest(quest_id),
    cycle_key VARCHAR(30) NOT NULL,
    progress_value INTEGER NOT NULL DEFAULT 0 CHECK (progress_value >= 0),
    completion_status BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP,
    reward_status BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (user_id, quest_id, cycle_key),
    CHECK (completed_at IS NULL OR completion_status)
);

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    notification_type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    read_status BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recommendation_config (
    recommendation_config_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(50) NOT NULL UNIQUE,
    distance_limit NUMERIC(10,2) NOT NULL CHECK (distance_limit > 0),
    cluster_count INTEGER NOT NULL CHECK (cluster_count > 0),
    status VARCHAR(20) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE recommendation_criterion (
    criterion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE recommendation_weight (
    recommendation_config_id BIGINT NOT NULL REFERENCES recommendation_config(recommendation_config_id),
    criterion_id BIGINT NOT NULL REFERENCES recommendation_criterion(criterion_id),
    weight_value NUMERIC(6,4) NOT NULL CHECK (weight_value >= 0),
    PRIMARY KEY (recommendation_config_id, criterion_id)
);

CREATE TABLE place_feature (
    place_feature_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id BIGINT NOT NULL REFERENCES place(place_id),
    recommendation_config_id BIGINT NOT NULL REFERENCES recommendation_config(recommendation_config_id),
    cluster_number INTEGER CHECK (cluster_number >= 0),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (place_id, recommendation_config_id)
);

CREATE TABLE place_feature_value (
    place_feature_id BIGINT NOT NULL REFERENCES place_feature(place_feature_id),
    criterion_id BIGINT NOT NULL REFERENCES recommendation_criterion(criterion_id),
    feature_value DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (place_feature_id, criterion_id)
);

-- Foreign-key and common access-path indexes not covered by primary/unique keys.
CREATE INDEX step_data_user_start_idx ON step_data (user_id, start_time DESC);
CREATE INDEX place_region_idx ON place (region_id);
CREATE INDEX place_type_idx ON place (place_type_id);
CREATE INDEX virtual_location_region_idx ON virtual_location (region_id);
CREATE INDEX virtual_location_nearest_place_idx ON virtual_location (nearest_place_id);
CREATE INDEX place_image_place_idx ON place_image (place_id);
CREATE INDEX journey_destination_idx ON journey (destination_place_id);
CREATE INDEX journey_start_place_idx ON journey (start_place_id);
CREATE INDEX journey_user_started_idx ON journey (user_id, started_at DESC);
CREATE INDEX user_discovered_place_place_idx ON user_discovered_place (place_id);
CREATE INDEX collection_card_card_idx ON collection_card (card_id);
CREATE INDEX user_card_card_idx ON user_card (card_id);
CREATE INDEX user_item_item_idx ON user_item (item_id);
CREATE INDEX quest_reward_item_idx ON quest (reward_item_id);
CREATE INDEX quest_progress_quest_idx ON quest_progress (quest_id);
CREATE INDEX notification_user_created_idx ON notification (user_id, created_at DESC);
CREATE INDEX recommendation_weight_criterion_idx ON recommendation_weight (criterion_id);
CREATE INDEX place_feature_config_idx ON place_feature (recommendation_config_id);
CREATE INDEX place_feature_value_criterion_idx ON place_feature_value (criterion_id);

-- Retain the specified numeric coordinates and index their spatial representation.
CREATE INDEX place_geography_idx ON place USING GIST (
    (ST_SetSRID(ST_MakePoint(longitude::DOUBLE PRECISION, latitude::DOUBLE PRECISION), 4326)::geography)
);
CREATE INDEX virtual_location_geography_idx ON virtual_location USING GIST (
    (ST_SetSRID(ST_MakePoint(longitude::DOUBLE PRECISION, latitude::DOUBLE PRECISION), 4326)::geography)
);

COMMIT;
